export type Token = (typeof TOKENS)[number];
export type Palette = Record<Token, string>;

export type ThemeName =
  'okyanus' | 'kor' | 'geceyarisi' | 'noirisik' | 'noir' | 'nane' | 'zeytin' | 'adacayi' | 'pudra';

export type ThemeDef = {
  name: ThemeName;
  label: string;
  note: string;
  scheme: 'dark' | 'light';
  colors: Palette;
  /** Gradyanlı temalarda üstten ışık, kart ve buton gradyanları; düz temalarda null (her şey düz renk). */
  gradients: ThemeGradients | null;
};

/** 135°, iki duraklı (0% → 100%) gradyan: [başlangıç, bitiş]. */
export type GradientPair = readonly [string, string];

export type ThemeGradients = {
  /** "Üstten ışık": ekranın tepesinden yayılan elips. g1 merkezde (0%), g2 ortada (45%), 75%'te şeffaf. */
  bgGlow: { g1: string; g2: string };
  /** Ana butonlar (a1: Paylaş, Gönder, Kaydet…). */
  btnGradient: GradientPair;
  /** a2 renkli kartlar (duyurular, sabitlenmiş içerik). */
  annGradient: GradientPair;
  /** a1 renkli kartlar (görev kartları). */
  taskGradient: GradientPair;
  /** Seçili çip ve segment butonları. */
  chipGradient: GradientPair;
  /** "Bende" gibi koyu rozetler. */
  badgeGradient: GradientPair;
  /** Alt menüde aktif sekmenin arka planı. */
  pillGradient: GradientPair;
  /** Butonların üst kenarındaki ince parıltı (inset gölge). */
  highlight: string;
  /** Normal surface kartlarının gölgesi (sadece Nane). */
  cardShadow?: string;
};

