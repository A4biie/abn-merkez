/** Varsayılan: sistem koyu moddaysa Gece Yarısı, açık moddaysa Nane. */
export function defaultTheme(scheme: 'dark' | 'light' | null | undefined): ThemeName {
  return scheme === 'light' ? 'nane' : 'geceyarisi';
}

/** Kaldırılan temalar yenilerine taşınır (veritabanındaki migration ile aynı eşleme). */
const LEGACY: Record<string, ThemeName> = {
  dark: 'geceyarisi',
  gece: 'geceyarisi',
  indigo: 'geceyarisi',
  gunbatimi: 'geceyarisi',
  light: 'nane',
  gul: 'nane',
  tropik: 'nane',
};

export function isThemeName(v: unknown): v is ThemeName {
  return typeof v === 'string' && Object.prototype.hasOwnProperty.call(THEMES, v);
}

/** Kayıtlı bir tema adını geçerli bir temaya çevirir (eskiyse yenisine, bilinmiyorsa null). */
export function resolveTheme(v: unknown): ThemeName | null {
  if (isThemeName(v)) return v;
  return typeof v === 'string' && Object.prototype.hasOwnProperty.call(LEGACY, v) ? LEGACY[v] : null;
}
